"""Generate the open-source credits from one data file.

Reads data/third_party.json and writes BOTH:
  1. THIRD_PARTY.md (repo root)
  2. the OPEN SOURCE card body in index.html (between the
     CREDITS:BEGIN / CREDITS:END markers)

Usage: python scripts/gen_credits.py
Stdlib only. Re-running must produce no diff (idempotent).
"""
import html
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "third_party.json")
MD_OUT = os.path.join(ROOT, "THIRD_PARTY.md")
PAGE = os.path.join(ROOT, "index.html")
BEGIN = "<!-- CREDITS:BEGIN -->"
END = "<!-- CREDITS:END -->"


def title_of(item):
    bits = [item["name"].upper()]
    if item.get("version"):
        bits.append(item["version"])
    text = " ".join(bits)
    if item.get("license"):
        text += " \u2014 " + item["license"]
    return text


def md_links(item):
    return " ".join("[%s](%s)" % (l["label"], l["url"])
                     for l in item.get("links", []))


def html_links(item):
    return " \u00b7 ".join(
        '<a href="%s" target="_blank" rel="noopener">%s</a>'
        % (html.escape(l["url"], quote=True), html.escape(l["label"]))
        for l in item.get("links", []))


def md_body(item):
    paras = [title_of(item), "",
             item.get("blurb", "")]
    if item.get("credit"):
        paras[-1] += " " + item["credit"]
    links = md_links(item)
    if links:
        paras[-1] += " " + links
    return "\n".join(paras).rstrip() + "\n"


def html_body(item):
    para = html.escape(item.get("blurb", ""))
    if item.get("credit"):
        para += " " + html.escape(item["credit"])
    links = html_links(item)
    if links:
        para += " " + links
    return ("    <h3>%s</h3>\n    <p>%s</p>\n"
            % (html.escape(title_of(item)), para))


def main():
    with open(DATA, encoding="utf-8") as f:
        data = json.load(f)
    items = data["items"]

    md = ("<!-- Generated by scripts/gen_credits.py from "
          "data/third_party.json. Do not edit by hand. -->\n"
          "# Third-party software\n\n%s\n" % data["intro"])
    for item in items:
        md += "\n## %s\n" % title_of(item)
        md += md_body(item).split("\n", 2)[-1]
    with open(MD_OUT, "w", encoding="utf-8") as f:
        f.write(md)

    block = "    <p>%s</p>\n" % html.escape(data["intro"])
    for item in items:
        block += html_body(item)
    with open(PAGE, encoding="utf-8") as f:
        page = f.read()
    if page.count(BEGIN) != 1 or page.count(END) != 1:
        raise SystemExit("credits markers missing or duplicated in index.html")
    head, rest = page.split(BEGIN)
    _, tail = rest.split(END)
    page = head + BEGIN + "\n" + block + "    " + END + tail
    with open(PAGE, "w", encoding="utf-8") as f:
        f.write(page)
    print("wrote %s (%d items) + index.html credits block"
          % (MD_OUT, len(items)))


if __name__ == "__main__":
    main()
