"""Generate the open-source credits from one data file.

Reads data/third_party.json and writes BOTH:
  1. THIRD_PARTY.md (repo root, grouped markdown tables)
  2. the OPEN SOURCE card body in index.html (grouped HTML tables,
     between the CREDITS:BEGIN / CREDITS:END markers)

Usage: python scripts/gen_credits.py
Stdlib only. Re-running must produce no diff (idempotent).
"""
import html
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "third_party.json")
MD_OUT = os.path.join(ROOT, "THIRD_PARTY.md")
PAGE = os.path.join(ROOT, "index.html")
BEGIN = "<!-- CREDITS:BEGIN -->"
END = "<!-- CREDITS:END -->"

GROUP_ORDER = ["Backend", "AI & RAG", "Video", "3D & assets"]


def grouped(items):
    out = {g: [] for g in GROUP_ORDER}
    notes = []
    for item in items:
        g = item.get("group", "")
        if g in out:
            out[g].append(item)
        else:
            notes.append(item)
    return out, notes


def md_links(item):
    return " &middot; ".join("[%s](%s)" % (l["label"], l["url"])
                             for l in item.get("links", []))


def html_links(item):
    return " &middot; ".join(
        '<a href="%s" target="_blank" rel="noopener">%s</a>'
        % (html.escape(l["url"], quote=True), html.escape(l["label"]))
        for l in item.get("links", []))


def md_cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ")


def md_table(items):
    rows = ["| Name | Version | License | What we use it for | Link |",
            "| --- | --- | --- | --- | --- |"]
    for item in items:
        what = item.get("blurb", "")
        if item.get("credit"):
            what += " " + item["credit"]
        rows.append("| %s | %s | %s | %s | %s |"
                    % (md_cell(item["name"]),
                       md_cell(item.get("version", "")) or "—",
                       md_cell(item.get("license", "")) or "—",
                       md_cell(what), md_cell(md_links(item))))
    return "\n".join(rows) + "\n"


def html_table(items):
    rows = ['    <div class="credwrap"><table class="credtab">',
            "    <tr><th>Name</th><th>Version</th><th>License</th>"
            "<th>What we use it for</th><th>Link</th></tr>"]
    for item in items:
        what = html.escape(item.get("blurb", ""))
        if item.get("credit"):
            what += " " + html.escape(item["credit"])
        links = html_links(item)
        rows.append("    <tr><td>%s</td><td>%s</td><td>%s</td>"
                    "<td>%s</td><td>%s</td></tr>"
                    % (html.escape(item["name"]),
                       html.escape(item.get("version", "")) or "—",
                       html.escape(item.get("license", "")) or "—",
                       what, links or "—"))
    rows.append("    </table></div>")
    return "\n".join(rows) + "\n"


def main():
    with open(DATA, encoding="utf-8") as f:
        data = json.load(f)
    items = data["items"]
    groups, notes = grouped(items)

    md = ("<!-- Generated by scripts/gen_credits.py from "
          "data/third_party.json. Do not edit by hand. -->\n"
          "# Third-party software\n\n%s\n" % data["intro"])
    for g in GROUP_ORDER:
        if not groups[g]:
            continue
        md += "\n## %s\n\n" % g
        md += md_table(groups[g])
    for item in notes:
        md += "\n*%s:* %s\n" % (item["name"],
                                md_cell(item.get("blurb", "")))
    with open(MD_OUT, "w", encoding="utf-8") as f:
        f.write(md)

    block = "    <p>%s</p>\n" % html.escape(data["intro"])
    for g in GROUP_ORDER:
        if not groups[g]:
            continue
        block += "    <h3>%s</h3>\n" % html.escape(g.upper())
        block += html_table(groups[g])
    for item in notes:
        block += '    <p class="crednote"><i>%s:</i> %s</p>\n' % (
            html.escape(item["name"]),
            html.escape(item.get("blurb", "")))
    with open(PAGE, encoding="utf-8") as f:
        page = f.read()
    if page.count(BEGIN) != 1 or page.count(END) != 1:
        raise SystemExit("credits markers missing or duplicated in index.html")
    head, rest = page.split(BEGIN)
    _, tail = rest.split(END)
    page = head + BEGIN + "\n" + block + "    " + END + tail
    with open(PAGE, "w", encoding="utf-8") as f:
        f.write(page)
    print("wrote %s (%d items) + index.html credits block"
          % (MD_OUT, len(items)))


if __name__ == "__main__":
    main()
